<#
    ACT 3: FOREVER

    2 - Scheduled report.

    Fan-out multiplied the work by servers. Scheduling multiplies it by time.

    The script you run once is worth an afternoon. The script that runs at 6am
    every day for three years is worth a headcount -- and the difference between
    the two is about ten minutes of setup.

    This generates a daily job-failure report, writes it as a standalone script,
    and registers it with Windows Task Scheduler.
#>

. "$PSScriptRoot\..\_Setup\Environment.ps1"


<# ---------- PARAMETERS ---------- #>

    $ReportName   = 'Daily Job Report'
    $ReportRoot   = Join-Path $LabRoot 'Reports'
    $ScriptPath   = Join-Path $ReportRoot 'DailyJobReport.ps1'
    $RunAt        = '06:00'

    # Email settings live inside the GENERATED script further down, not here --
    # the scheduled task runs that file, not this one.

    if (-not (Test-Path $ReportRoot)) { New-Item -ItemType Directory -Path $ReportRoot -Force | Out-Null }


<# ---------- 1. Write the report script ---------- #>

<#
    A scheduled task runs in its own process, with no memory of this session. So
    the generated script has to stand alone: import the module, define its own
    targets, and not depend on anything we have in scope right now.

    A single-quoted here-string keeps everything literal -- nothing is expanded
    when we WRITE the file, only when the file RUNS.
#>

    $reportScript = @'
#Requires -Modules dbatools
<#
    Daily job failure report. Generated by the SQL Saturday Boston session scripts.
    Runs unattended from Task Scheduler.
#>

Import-Module dbatools

$Targets    = 'localhost,14317','localhost,14319','localhost,14322','localhost,14325'
$ReportRoot = 'C:\SQLSatLab\Reports'
$Stamp      = Get-Date -Format 'yyyy-MM-dd'
$OutFile    = Join-Path $ReportRoot "JobReport_$Stamp.html"

Set-DbatoolsConfig -FullName sql.connection.trustcert -Value $true
Set-DbatoolsConfig -FullName sql.connection.encrypt   -Value $false

# Lab only. On real servers the task runs as a service account with Windows auth,
# and you delete these two lines and every @Lab below.
$LabCredential = [pscredential]::new('sa', (ConvertTo-SecureString 'SqlSat#Boston2026' -AsPlainText -Force))
$Lab = @{ SqlCredential = $LabCredential }

$style = @"
<style>
 body  { font-family:Segoe UI,Arial,sans-serif; font-size:11pt; background:#fafafa; }
 table { border-collapse:collapse; margin:12px 0; }
 td,th { border:1px solid #ccc; padding:4px 8px; }
 th    { background:#222; color:#fff; text-align:left; }
 tr:nth-child(even) { background:#f0f0f0; }
 h2    { color:#222; }
</style>
"@

$fragments = @()

# --- Failures in the last 24 hours ---
$failed = Get-DbaAgentJobHistory -SqlInstance $Targets @Lab -StartDate (Get-Date).AddDays(-1) -ExcludeJobSteps |
          Where-Object Status -eq 'Failed' |
          Select-Object SqlInstance, Job, RunDate, Duration, Message

$fragments += "<h2>Failed jobs (last 24 hours)</h2>"
$fragments += if ($failed) { $failed | ConvertTo-Html -Fragment } else { "<p>None.</p>" }

# --- Enabled but never run ---
$never = Get-DbaAgentJob -SqlInstance $Targets @Lab |
         Where-Object { $_.IsEnabled -and $_.LastRunDate -lt [datetime]'1900-01-01' } |
         Select-Object SqlInstance, Name

$fragments += "<h2>Enabled but never run</h2>"
$fragments += if ($never) { $never | ConvertTo-Html -Fragment } else { "<p>None.</p>" }

# --- Backup gaps ---
$gaps = Get-DbaLastBackup -SqlInstance $Targets @Lab |
        Where-Object { -not $_.LastFullBackup -or $_.LastFullBackupIsCopyOnly } |
        Select-Object SqlInstance, Database, LastFullBackup, LastFullBackupIsCopyOnly

$fragments += "<h2>Backup problems</h2>"
$fragments += if ($gaps) { $gaps | ConvertTo-Html -Fragment } else { "<p>None.</p>" }

ConvertTo-Html -Head $style -Body ($fragments -join "`n") `
    -PostContent "<hr><i>Generated $(Get-Date) on $env:COMPUTERNAME</i>" |
    Out-File -FilePath $OutFile -Encoding utf8

Write-Output "Report written to $OutFile"

# --- Optional email ---
# Send-MailMessage is deprecated but still ubiquitous. For anything new, use
# Microsoft Graph, or Send-MailKitMessage from the PSGallery.
#
# Send-MailMessage -SmtpServer 'smtp.yourcompany.com' `
#     -From 'sqlalerts@yourcompany.com' -To 'dba-team@yourcompany.com' `
#     -Subject "SQL job report $Stamp" -Body (Get-Content $OutFile -Raw) -BodyAsHtml
'@

    $reportScript | Set-Content -Path $ScriptPath -Encoding UTF8
    Write-Host "Report script written to $ScriptPath" -ForegroundColor Green


<# ---------- 2. Prove it works BEFORE you schedule it ---------- #>

<#
    The single most common mistake: register the task, walk away, and discover in
    three weeks that it has been failing silently every morning. Run it by hand
    first.
#>

    & $ScriptPath


<# ---------- 3. Register the scheduled task ---------- #>

<#
    The modern cmdlets (New-ScheduledTask* ) are much easier to read than the XML
    approach, and they are built in -- no module required.
#>

    $action    = New-ScheduledTaskAction -Execute 'powershell.exe' `
                     -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$ScriptPath`""

    $trigger   = New-ScheduledTaskTrigger -Daily -At $RunAt

    $settings  = New-ScheduledTaskSettingsSet -StartWhenAvailable `
                     -DontStopIfGoingOnBatteries -AllowStartIfOnBatteries `
                     -ExecutionTimeLimit (New-TimeSpan -Hours 2)

    Register-ScheduledTask -TaskName "_REPORT_$ReportName" `
        -Action $action -Trigger $trigger -Settings $settings `
        -Description 'Daily SQL Server job failure and backup report' `
        -RunLevel Highest -Force | Out-Null

    Write-Host "Scheduled task '_REPORT_$ReportName' registered for $RunAt daily." -ForegroundColor Green


<# ---------- 4. Check it ---------- #>

    Get-ScheduledTask -TaskName "_REPORT_$ReportName" |
        Select-Object TaskName, State, @{ n = 'NextRun'; e = { ($_ | Get-ScheduledTaskInfo).NextRunTime } }

    # Run it right now rather than waiting until 6am
    Start-ScheduledTask -TaskName "_REPORT_$ReportName"

    Start-Sleep -Seconds 5
    Get-ScheduledTaskInfo -TaskName "_REPORT_$ReportName" |
        Select-Object TaskName, LastRunTime, LastTaskResult, NextRunTime

    # LastTaskResult of 0 means success. Anything else is a problem.

    Get-ChildItem $ReportRoot -Filter *.html | Sort-Object LastWriteTime -Descending | Select-Object -First 3


<# ---------- Running as a service account ---------- #>

<#
    A task registered under YOUR account stops working the day you change your
    password or leave. In production use a dedicated service account with a
    non-expiring password and "Log on as a batch job" rights:

        $cred = Get-Credential
        Register-ScheduledTask -TaskName "_REPORT_$ReportName" `
            -Action $action -Trigger $trigger -Settings $settings `
            -User $cred.UserName -Password $cred.GetNetworkCredential().Password `
            -RunLevel Highest -Force

    Or use a Group Managed Service Account (gMSA) and have no password at all.
#>


<# ---------- Task Scheduler or SQL Agent? ---------- #>

<#
    Both work. Roughly:

      SQL Agent          already exists, already monitored, already has operators
                         and failure notification. Best when the work is entirely
                         inside one SQL Server. Needs the PowerShell subsystem, or
                         a CmdExec step calling powershell.exe.

      Task Scheduler     runs from a central admin box that reaches ALL your
                         servers. Better for estate-wide reporting like this,
                         and it keeps working when one SQL Server is down --
                         which is exactly when you want the report.

    For a fleet report, Task Scheduler on a management server is usually right.
#>


